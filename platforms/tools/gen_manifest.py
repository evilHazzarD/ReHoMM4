#!/usr/bin/env python3
"""The in-app installer's manifest: path, size and SHA-256 of each game file (no game content).

    python3 -I platforms/tools/gen_manifest.py game > h4/src/install/manifest_en.inc

From an install made from GOG's English offline installer (tools/build.sh unpacks it into game/).
GOG's installer helpers (tmp, __redist, app, commonappdata) are left out: the Galaxy download of
the same build has exactly the rest (checked against its depot MD5s), so one manifest verifies
both ways of installing.
"""
import hashlib
import os
import sys

SKIP_TOP = {"tmp", "__redist", "app", "commonappdata"}


def main(root):
    rows = []
    for d, dirs, files in os.walk(root):
        rel_d = os.path.relpath(d, root)
        if rel_d == ".":
            dirs[:] = [x for x in dirs if x.lower() not in SKIP_TOP]
        for n in files:
            full = os.path.join(d, n)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            h = hashlib.sha256()
            with open(full, "rb") as f:
                for b in iter(lambda: f.read(1 << 20), b""):
                    h.update(b)
            rows.append((rel, os.path.getsize(full), h.hexdigest()))
    rows.sort(key=lambda r: r[0].lower())
    print("// Generated by platforms/tools/gen_manifest.py from GOG's English Heroes IV Complete 3.0")
    print("// (setup_..._3.0_win11_gog_0.2_(76223)): path, size, SHA-256. No game content.")
    print(f"// {len(rows)} files, {sum(r[1] for r in rows)} bytes.")
    for rel, size, sha in rows:
        print(f'{{"{rel}", {size}ull, "{sha}"}},')


if __name__ == "__main__":
    main(sys.argv[1])
